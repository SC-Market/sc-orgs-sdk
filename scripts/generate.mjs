#!/usr/bin/env node
/**
 * Regenerate the typed client from the live SC Orgs spec.
 *
 *   npm run generate              fetch the live spec, update openapi/, regenerate
 *   npm run generate -- --offline regenerate from openapi/public-v1.json
 *   npm run generate -- --check   exit 1 if the live spec differs from openapi/ (writes nothing)
 *
 * Source: https://api.sc-orgs.space/api/v1/openapi.json. Webhook payloads and
 * signatures aren't in the spec: they are hand-written in src/webhooks.ts and
 * python/src/sc_orgs_sdk/webhooks.py, following the server's signing code.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { pyOperations, pySchemas, tsOperations, tsSchemas } from "./lib/codegen.mjs"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const API = process.env.SC_ORGS_API_ORIGIN ?? "https://api.sc-orgs.space"
const SOURCE = { url: `${API}/api/v1/openapi.json`, file: "openapi/public-v1.json" }

const args = new Set(process.argv.slice(2))
const offline = args.has("--offline")
const check = args.has("--check")

const stable = (v) => `${JSON.stringify(v, null, 2)}\n`
const write = (rel, text) => {
  mkdirSync(dirname(join(ROOT, rel)), { recursive: true })
  writeFileSync(join(ROOT, rel), text)
  console.log(`  wrote ${rel}`)
}

let spec
if (offline) spec = JSON.parse(readFileSync(join(ROOT, SOURCE.file), "utf8"))
else {
  console.log(`Fetching ${SOURCE.url}`)
  const res = await fetch(SOURCE.url, { headers: { Accept: "application/json" } })
  if (!res.ok) throw new Error(`${SOURCE.url}: HTTP ${res.status}`)
  spec = await res.json()
}

if (check) {
  const changed = readFileSync(join(ROOT, SOURCE.file), "utf8") !== stable(spec)
  console.log(changed ? `changed: ${SOURCE.file}\nThe live API changed: run \`npm run generate\`.` : "Up to date.")
  process.exit(changed ? 1 : 0)
}

const source = `openapi/public-v1.json (${spec.info.title} ${spec.info.version})`
const tsHeader = `// Generated by scripts/generate.mjs from ${source}. Do not edit: run \`npm run generate\`.\n`
const pyHeader = `# Generated by scripts/generate.mjs from ${source}. Do not edit: run \`npm run generate\`.\n`

if (!offline) write(SOURCE.file, stable(spec))
write("src/generated/types.ts", tsSchemas(spec.components.schemas, tsHeader))
write("src/generated/client.ts", tsOperations(spec, { className: "GeneratedScOrgsClient", baseImport: "../http.js", header: tsHeader }))
write("python/src/sc_orgs_sdk/_types.py", pySchemas(spec.components.schemas, pyHeader))
write("python/src/sc_orgs_sdk/_operations.py", pyOperations(spec, { className: "GeneratedScOrgsClient", header: pyHeader }))
console.log("Done. Run `npm run build && npm test` and `cd python && python3 -m unittest discover -s tests` next.")
